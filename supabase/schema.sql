update public.dcd_borradores
set
    codigo_expediente = coalesce(codigo_expediente, codigo_borrador),
    version_num = coalesce(version_num, 1),
    saved_at = coalesce(saved_at, updated_at, created_at),
    is_latest = coalesce(is_latest, true)
where codigo_expediente is null
   or version_num is null
   or saved_at is null;

update public.dcd_registros r
set
    codigo_expediente = coalesce(r.codigo_expediente, b.codigo_expediente),
    version_num = coalesce(r.version_num, b.version_num)
from public.dcd_borradores b
where r.codigo_borrador = b.codigo_borrador
  and (r.codigo_expediente is null or r.version_num is null);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

